import { buildRadiusScale, findBadRadii } from "./radius.js";
import { findGlowShadows } from "./shadow.js";
import { GENERATED_FILE_EXEMPT_RULES, LINT_RULES, type Rule, type Violation } from "./types.js";

// 3, 4, 6 or 8 hex digits. Not preceded by a word char or `&` (HTML entities) and not
// followed by a word char or `-` (so `#abc-panel` selectors and 5/7-digit runs do not match).
const HEX_COLOR = /(?<![\w&#])#(?:[0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{3,4})(?![\w-])/g;

// Any Tailwind class with a bracket group (`w-[13px]`, `data-[state=open]:p-2`), plus
// arbitrary variants such as `[&>*]:p-2`.
const ARBITRARY_CLASS = /(?<![\w\]-])[-!]?[a-z][a-z0-9-]*-\[[^\]\s]+\]|(?<![\w\]-])\[&[^\]\s]*\]:/g;

// Gradient functions (including `repeating-*`) and the Tailwind gradient utilities.
const GRADIENT =
  /\b(?:linear|radial|conic)-gradient\(|(?<=^|[\s"'`:!])bg-(?:gradient-to-[a-z]{1,2}|(?:linear|radial|conic)(?:-|(?=$|[\s"'`}),;>])))/gm;

function offsets(content: string, pattern: RegExp): number[] {
  return Array.from(content.matchAll(pattern), (m) => m.index);
}

/** Start offset of each line, so a match offset maps to a 1-based line number. */
function lineStarts(content: string): number[] {
  const starts = [0];
  for (let i = 0; i < content.length; i++) {
    if (content[i] === "\n") {
      starts.push(i + 1);
    }
  }
  return starts;
}

function lineOf(starts: number[], offset: number): number {
  let lo = 0;
  let hi = starts.length - 1;
  while (lo < hi) {
    const mid = (lo + hi + 1) >> 1;
    if ((starts[mid] as number) <= offset) {
      lo = mid;
    } else {
      hi = mid - 1;
    }
  }
  return lo + 1;
}

/**
 * Scan one file for Off_System_Values.
 *
 * `tokenRadiusScale` lists the allowed radii as Token_File keys and/or values.
 * For files generated by the Token_Generator, only hex-color, glow-shadow and
 * bad-radius are skipped; arbitrary-tailwind and gradient still apply.
 *
 * Results are ordered by line, then by rule order in `LINT_RULES`.
 */
export function scanFile(
  path: string,
  content: string,
  tokenRadiusScale: readonly string[],
  isGeneratedFile: boolean,
): Violation[] {
  const exempt: readonly Rule[] = isGeneratedFile ? GENERATED_FILE_EXEMPT_RULES : [];
  const radiusScale = buildRadiusScale(tokenRadiusScale);
  const finders: Record<Rule, () => number[]> = {
    "hex-color": () => offsets(content, HEX_COLOR),
    "arbitrary-tailwind": () => offsets(content, ARBITRARY_CLASS),
    "glow-shadow": () => findGlowShadows(content),
    gradient: () => offsets(content, GRADIENT),
    "bad-radius": () => findBadRadii(content, radiusScale),
  };
  const starts = lineStarts(content);
  const found: Array<Violation & { order: number }> = [];
  for (const [order, rule] of LINT_RULES.entries()) {
    if (exempt.includes(rule)) {
      continue;
    }
    for (const offset of finders[rule]()) {
      found.push({ file: path, line: lineOf(starts, offset), rule, order });
    }
  }
  found.sort((a, b) => a.line - b.line || a.order - b.order);
  return found.map(({ file, line, rule }) => ({ file, line, rule }));
}
